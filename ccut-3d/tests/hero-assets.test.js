const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');

function loadManifest() {
  const modulePath = path.join(root, 'hero-assets.js');
  assert.equal(fs.existsSync(modulePath), true, 'hero-assets.js should define the browser asset contract');
  delete require.cache[require.resolve(modulePath)];
  return require(modulePath).HERO_ASSETS;
}

function readGlbJson(filePath) {
  const file = fs.readFileSync(filePath);
  assert.equal(file.subarray(0, 4).toString('ascii'), 'glTF', `${path.basename(filePath)} should be a binary glTF file`);
  assert.equal(file.readUInt32LE(4), 2, `${path.basename(filePath)} should use glTF 2.0`);
  const jsonLength = file.readUInt32LE(12);
  assert.equal(file.subarray(16, 20).toString('ascii'), 'JSON', `${path.basename(filePath)} should begin with a JSON chunk`);
  return JSON.parse(file.subarray(20, 20 + jsonLength).toString('utf8').trim());
}

test('hero manifest defines independently replaceable main building, stone and tree assets', () => {
  const manifest = loadManifest();

  assert.deepEqual(Object.keys(manifest), ['mainBuilding', 'plazaStone', 'autumnTree']);
  assert.equal(manifest.mainBuilding.url, 'assets/models/main-building.glb?v=photo-facade-3');
  assert.equal(manifest.plazaStone.url, 'assets/models/plaza-stone.glb');
  assert.equal(manifest.autumnTree.url, 'assets/models/autumn-tree.glb');
  assert.equal(manifest.mainBuilding.fallbackTag, 'mainBuilding');
  assert.equal(manifest.plazaStone.fallbackName, 'main-plaza-stone');
  assert.deepEqual(manifest.plazaStone.fallbackNames, ['main-plaza-stone', 'main-plaza-planter']);
  assert.equal(manifest.autumnTree.fallbackName, 'main-plaza-tree');
  for (const asset of Object.values(manifest)) {
    assert.equal(asset.position.length, 3);
    assert.equal(asset.rotation.length, 3);
    assert.equal(asset.scale.length, 3);
  }
});

test('page cache-busts the current realistic main-building hero manifest', () => {
  const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  assert.match(html, /hero-assets\.js\?v=photo-facade-3/);
});

test('Blender exports valid named GLB assets within the competition page budget', () => {
  const manifest = loadManifest();
  const requiredNodes = {
    mainBuilding: [
      'MainBuilding', 'WarmWindows', 'CurvedWing', 'TopArchWindow',
      'GroundArchWindow', 'SidePediment', 'CentralPediment',
      'RearFacadeWindow', 'RearGroundWindow', 'RearDoor',
    ],
    plazaStone: ['PlazaStone', 'StonePlanter'],
    autumnTree: ['AutumnTree', 'WhitewashedTrunk', 'AutumnFoliage'],
  };
  let totalBytes = 0;

  for (const [id, asset] of Object.entries(manifest)) {
    const filePath = path.join(root, asset.url.split('?')[0]);
    assert.equal(fs.existsSync(filePath), true, `${asset.url} should be generated by Blender`);
    totalBytes += fs.statSync(filePath).size;
    const gltf = readGlbJson(filePath);
    const names = new Set((gltf.nodes || []).map((node) => node.name));
    for (const nodeName of requiredNodes[id]) {
      assert.equal(names.has(nodeName), true, `${asset.url} should contain ${nodeName}`);
    }
  }

  assert.ok(totalBytes <= 15 * 1024 * 1024, `hero GLBs should stay under 15 MB total (got ${totalBytes} bytes)`);
});

test('main building batches static geometry and records a complete provisional rear facade', () => {
  const manifest = loadManifest();
  const gltf = readGlbJson(path.join(root, manifest.mainBuilding.url.split('?')[0]));
  const meshNodeCount = (gltf.nodes || []).filter((node) => Number.isInteger(node.mesh)).length;
  assert.ok(meshNodeCount <= 16, `main building should use at most 16 draw-call mesh nodes (got ${meshNodeCount})`);

  const main = (gltf.nodes || []).find((node) => node.name === 'MainBuilding');
  assert.ok(main && main.extras && main.extras.rearFacade, 'main building should record rear facade coverage');
  assert.ok(main.extras.rearFacade.rectangularWindows >= 150);
  assert.ok(main.extras.rearFacade.topArches >= 20);
  assert.ok(main.extras.rearFacade.groundArches >= 15);
  assert.ok(main.extras.rearFacade.pilasters >= 20);

  const rearDoor = (gltf.nodes || []).find((node) => node.name === 'RearDoor');
  const rearDoorZ = rearDoor && (rearDoor.translation ? rearDoor.translation[2] : rearDoor.matrix && rearDoor.matrix[14]);
  assert.ok(rearDoor && rearDoorZ < -10, 'rear door marker should remain on the rear side');
});

test('main building GLB carries the approved close-up realism contract', () => {
  const manifest = loadManifest();
  const gltf = readGlbJson(path.join(root, manifest.mainBuilding.url.split('?')[0]));
  const materials = new Set((gltf.materials || []).map((material) => material.name));
  const main = (gltf.nodes || []).find((node) => node.name === 'MainBuilding');

  for (const name of [
    'Brick PBR surface',
    'Limestone PBR surface',
    'Carved stone PBR surface',
    'Window recess shadow',
    'Blue dusk glass',
  ]) assert.equal(materials.has(name), true, `main building should export ${name}`);

  assert.equal(main.extras.realism.recessedWindows, true);
  assert.equal(main.extras.realism.beveledMasonry, true);
  assert.equal(main.extras.realism.facadeModuleSystem, true);
  assert.equal(main.extras.realism.windowInteriors, true);
  assert.equal(main.extras.realism.surfaceWeathering, true);
  assert.ok(main.extras.realism.warmWindowRatio <= 0.2);
  assert.deepEqual(main.extras.realism.surfacePatterns, ['brick', 'stone', 'glass']);
});

test('main building reproduces the photographed classical facade hierarchy', () => {
  const manifest = loadManifest();
  const gltf = readGlbJson(path.join(root, manifest.mainBuilding.url.split('?')[0]));
  const nodes = new Set((gltf.nodes || []).map((node) => node.name));
  const main = (gltf.nodes || []).find((node) => node.name === 'MainBuilding');

  for (const name of [
    'CentralRaisedAttic',
    'CentralUpperPediment',
    'SidePediment_L',
    'SidePediment_R',
    'FlutedPilaster',
    'CorinthianCapital',
    'CarvedReliefPanel',
    'EntrancePortico',
    'MainEntranceSteps',
  ]) assert.equal(nodes.has(name), true, `main building should expose ${name}`);

  assert.deepEqual(main.extras.photoFacade, {
    storeys: 7,
    centralPedimentTiers: 2,
    sidePediments: 2,
    entranceDoors: 3,
    flutedPilasters: true,
    carvedReliefPanels: true,
    stoneBaseCourse: true,
    curvedWings: true,
  });

  const featureMeshes = (gltf.nodes || []).filter((node) =>
    Number.isInteger(node.mesh) && node.name.startsWith('Batched_PhotoFacade_'));
  assert.ok(featureMeshes.length >= 4, 'photographed facade details should survive export as real batched meshes');
  const featureVertices = featureMeshes.reduce((total, node) => {
    const mesh = gltf.meshes[node.mesh];
    return total + mesh.primitives.reduce((meshTotal, primitive) =>
      meshTotal + gltf.accessors[primitive.attributes.POSITION].count, 0);
  }, 0);
  assert.ok(featureVertices >= 5000, `photographed facade should contain substantial geometry (got ${featureVertices} vertices)`);
});
